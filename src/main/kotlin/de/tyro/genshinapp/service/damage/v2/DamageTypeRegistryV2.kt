package de.tyro.genshinapp.service.damage.v2

import com.fasterxml.jackson.databind.ObjectMapper
import org.springframework.stereotype.Service

data class SharedDamageTypesV2(val schemaVersion: Int, val damageTypes: List<DamageTypeDefinitionV2>)

@Service
class DamageTypeRegistryV2(private val mapper: ObjectMapper) {
    val definitions: Map<String, DamageTypeDefinitionV2> by reloadableFormulaV2 {
        val catalog = DamageFormulaResourcesV2.resource("data/damage-formulas-v2/damage-types.json").inputStream.use {
            mapper.readValue(it, SharedDamageTypesV2::class.java)
        }
        require(catalog.schemaVersion == 2) { "Unsupported damage type catalog schema" }
        require(catalog.damageTypes.map { it.id }.distinct().size == catalog.damageTypes.size) { "Duplicate shared damage type IDs" }
        catalog.damageTypes.forEach { type ->
            require(type.id.isNotBlank() && type.element in setOf("Pyro", "Hydro", "Electro", "Cryo", "Dendro", "Anemo", "Geo", "Physical")) { "Invalid damage type '${type.id}'" }
            require(type.kind in setOf("talent", "lunar", "stellar", "reaction", "artifactProc")) { "Invalid damage kind for '${type.id}'" }
            require(type.defenseBehavior in setOf("standard", "bypass")) { "Invalid defense behavior for '${type.id}'" }
            require(type.resistanceInput.isNotBlank()) { "Missing resistance input for '${type.id}'" }
            require(type.elementalBonusInput == null) { "'elementalBonusInput' is generated by the calculator; use the damage type's element instead." }
            require(!type.appliesElementalDamageBonus || type.element != "Physical") { "Physical damage must disable elemental damage bonuses" }
        }
        catalog.damageTypes.associateBy { it.id }
    }
    fun resolve(ids: Collection<String>) = ids.distinct().map { id ->
        requireNotNull(definitions[id]) { "Unknown shared damage type '$id'. Define it in damage-types.json first." }
    }

    companion object {
        /** Keep the existing main-element control while adding separate RES controls for other elements. */
        fun resistanceInput(type: DamageTypeDefinitionV2, ownerElement: String): String = when {
            type.element.equals(ownerElement, true) && type.resistanceInput == "enemy${type.element}Resistance" -> "enemyResistance"
            !type.element.equals(ownerElement, true) && type.resistanceInput == "enemyResistance" -> "enemy${type.element}Resistance"
            else -> type.resistanceInput
        }
    }
}
